# ==========================================================
# 환경변수 로더
# ==========================================================
def get_env(key: str) -> str:
    """환경변수 안전 로딩 (없으면 즉시 에러)"""
    val = os.environ.get(key, "").strip()
    if not val:
        raise RuntimeError(f"환경변수 없음: {key}")
    return val
